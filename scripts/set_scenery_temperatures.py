#!/usr/bin/env python3
"""Give each piece of Blue Mountains scenery its own temperature.

Without this every terrain, rock, river and tree visual renders at the single
ambient temperature, so the thermal feed is one flat colour with only the
person standing out. This adds a Thermal plugin with a fixed <temperature> to
every <visual> in models/blue_mountains/model.sdf, the same mechanism the
person uses in worlds/large_demo.sdf.

Each surface type has a temperature range. Visuals of the same type are spread
across that range (each rock formation, each 10 m forest tile gets its own
value) so neighbouring pieces don't all read as one block. The spread is seeded
by the visual's link name, so values stay the same from run to run.

Safe to re-run: plugins it added before are replaced, not duplicated. Tune
SURFACES and run it again, then restart the sim:

    python3 scripts/set_scenery_temperatures.py

The thermal camera stores fixed temperatures in 8 bits, so they render in
steps of about 2.57 K (655.35 K / 255). A range narrower than that collapses
to one shade; ranges here are wide enough to land on two or three.

Keep every max below the ground station's person_min_k (305 K), or warm rock
will be mistaken for a person.
"""

import os
import random
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_SDF = os.path.join(HERE, '..', 'models', 'blue_mountains', 'model.sdf')

# Surface type -> (min K, max K). Rough mid-afternoon values: water coolest,
# canopy a little above air, open ground warmer, sun-baked sandstone warmest.
SURFACES = {
    'water':     (284.5, 286.0),
    'forest':    (288.0, 294.0),
    'terrain':   (295.0, 295.0),
    'gravel':    (297.0, 299.0),
    'talus':     (297.0, 301.0),
    'sandstone': (299.0, 303.0),
}

# Mesh file name -> surface type. First match wins.
MESH_RULES = [
    (r'river_water', 'water'),
    (r'gravel_bank', 'gravel'),
    (r'forest_terrain', 'terrain'),
    (r'^forest_\d+_\d+\.dae$', 'forest'),
    (r'talus|shelf', 'talus'),
    (r'sandstone|summit|buttress|crown|outcrop|hill', 'sandstone'),
]

PLUGIN_TAG = 'scenery temperature: generated by scripts/set_scenery_temperatures.py'


def surface_for(mesh_file):
    for pattern, surface in MESH_RULES:
        if re.search(pattern, mesh_file):
            return surface
    return None


def temperature_for(surface, link_name):
    lo, hi = SURFACES[surface]
    return random.Random(link_name).uniform(lo, hi)


def main():
    with open(MODEL_SDF) as f:
        sdf = f.read()

    # Drop what a previous run added.
    sdf = re.sub(
        r'[ \t]*<!-- ' + re.escape(PLUGIN_TAG) + r' -->\n'
        r'[ \t]*<plugin filename="ignition-gazebo-thermal-system".*?</plugin>\n',
        '', sdf, flags=re.S)

    added = {}
    unmatched = []

    def add_plugin(match):
        link_name, link = match.group(1), match.group(0)
        visual = re.search(r'<visual name=.*?</visual>', link, flags=re.S)
        if visual is None:
            return link
        mesh = re.search(r'<uri>model://blue_mountains/meshes/([^<]+)</uri>',
                         visual.group(0))
        surface = surface_for(mesh.group(1)) if mesh else None
        if surface is None:
            unmatched.append(link_name)
            return link
        kelvin = temperature_for(surface, link_name)
        added.setdefault(surface, []).append(kelvin)

        close = visual.end() - len('</visual>')
        indent = re.search(r'([ \t]*)$', link[:close]).group(1) + '  '
        block = (
            f'  <!-- {PLUGIN_TAG} -->\n'
            f'{indent}<plugin filename="ignition-gazebo-thermal-system" '
            f'name="ignition::gazebo::systems::Thermal">\n'
            f'{indent}  <temperature>{kelvin:.1f}</temperature>\n'
            f'{indent}</plugin>\n{indent[:-2]}'
        )
        return link[:close] + block + link[close:]

    sdf = re.sub(r'<link name="([^"]+)">.*?</link>', add_plugin, sdf,
                 flags=re.S)

    with open(MODEL_SDF, 'w') as f:
        f.write(sdf)

    for surface, temps in sorted(added.items()):
        print(f'{surface:10s} {len(temps):3d} visuals  '
              f'{min(temps):.1f}-{max(temps):.1f} K')
    if unmatched:
        print('left at ambient:', ', '.join(unmatched))


if __name__ == '__main__':
    main()
