#!/usr/bin/env python3
"""Scatter kangaroos and wombats across worlds/large_demo.sdf.

Picks random spots over the Blue Mountains scenery and writes an <include>
for each animal between the ANIMALS BEGIN/END comments in the world file.
Run it again to reshuffle (or with a different --seed):

    python3 scripts/place_animals.py
    python3 scripts/place_animals.py --kangaroos 8 --wombats 8 --seed 7

So that no animal clips into the ground, each spot is checked against the
scenery's own meshes (models/blue_mountains/model.sdf), with no Gazebo needed:
  - The ground height is sampled on a grid over the animal's footprint (its
    collision boxes, turned to its yaw) by dropping a ray straight down onto
    the terrain and rock collision meshes.
  - A plane is fitted to those samples and the animal is tilted to lie on
    it, then raised until every sample point of its footprint is above the
    ground, plus a small gap. Set down level on a slope instead, it lands on
    one foot first and the kangaroo (tall, narrow feet) rolls over.
  - Spots steeper than --max-slope, or bumpier than --max-step around the
    fitted plane (rock edges), are skipped.
  - Spots under water (the river is visual-only, so it has no collision),
    or near a tree trunk or crown, are skipped.
  - Animals stay clear of each other, of every casualty spot in
    run_blue_mountains.sh, and of the ute where the drones take off.

demo_animal and wombat1 (beside person1) are left alone: other scripts move
them by those names.
"""

import argparse
import math
import random
import re
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / 'models'
WORLD = ROOT / 'worlds' / 'large_demo.sdf'
NS = {'c': 'http://www.collada.org/2005/11/COLLADASchema'}

BEGIN = '<!-- ANIMALS BEGIN: generated by scripts/place_animals.py -->'
END = '<!-- ANIMALS END -->'

# The world rectangle the scenery covers (same as maps/blue_mountains_aerial),
# shrunk so no animal sits right on the edge.
X_RANGE = (-16.5, 49.0)
Y_RANGE = (-6.5, 34.5)

# Footprint in the model's own frame (x_min, x_max, y_min, y_max) and height,
# from the collision boxes in models/<animal>/model.sdf. Both models have
# their feet at z = 0 and face +y.
FOOTPRINT = {
    'kangaroo': ((-0.27, 0.27, -1.25, 0.42), 1.37),
    'wombat': ((-0.26, 0.26, -0.47, 0.54), 0.50),
}

# Places to keep clear: the casualty spots (run_blue_mountains.sh), the two
# animals already beside person1, and the ute with the drone pads.
KEEP_CLEAR = [
    (-6.36, -3.07, 4.0), (-6.36, 18.12, 4.0), (-3.7, 34.25, 4.0),
    (42.37, 20.97, 4.0), (36.2, 1.04, 4.0),
    (-5.2, -3.1, 3.0), (-7.5, -3.1, 3.0),
    (2.47, 0.0, 6.0),
]


def pose_matrix(text):
    """4x4 transform from an SDF 'x y z roll pitch yaw' string."""
    x, y, z, r, p, w = map(float, (text or '0 0 0 0 0 0').split())
    cr, sr, cp, sp, cw, sw = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(w), math.sin(w)
    m = np.eye(4)
    m[:3, :3] = [
        [cw * cp, cw * sp * sr - sw * cr, cw * sp * cr + sw * sr],
        [sw * cp, sw * sp * sr + cw * cr, sw * sp * cr - cw * sr],
        [-sp, cp * sr, cp * cr],
    ]
    m[:3, 3] = [x, y, z]
    return m


_mesh_cache = {}


def load_dae(uri):
    """Triangles (n, 3, 3) of a model:// COLLADA mesh, in its own frame."""
    if uri in _mesh_cache:
        return _mesh_cache[uri]
    root = ET.parse(MODELS / uri[len('model://'):]).getroot()
    ids = {e.get('id'): e for e in root.iter() if e.get('id')}
    tris = []
    for ts in root.iter('{%s}triangles' % NS['c']):
        inputs = ts.findall('c:input', NS)
        stride = max(int(i.get('offset')) for i in inputs) + 1
        vin = next(i for i in inputs if i.get('semantic') == 'VERTEX')
        src = ids[vin.get('source')[1:]]
        src = ids[src.find('c:input', NS).get('source')[1:]]
        pos = np.array(src.find('c:float_array', NS).text.split(), float).reshape(-1, 3)
        idx = np.array(ts.findtext('c:p', namespaces=NS).split(), int)
        idx = idx[int(vin.get('offset'))::stride].reshape(-1, 3)
        tris.append(pos[idx])
    _mesh_cache[uri] = np.concatenate(tris)
    return _mesh_cache[uri]


def mesh_tris(geom, transform):
    scale = np.array((geom.findtext('mesh/scale') or '1 1 1').split(), float)
    t = load_dae(geom.findtext('mesh/uri')) * scale
    return t @ transform[:3, :3].T + transform[:3, 3]


class Surface:
    """Triangles that a vertical ray can be dropped onto, binned on a 1 m grid."""

    def __init__(self, tris):
        self.tris = tris
        self.bins = {}
        lo = np.floor(tris[:, :, :2].min(axis=1)).astype(int)
        hi = np.floor(tris[:, :, :2].max(axis=1)).astype(int)
        for i, (a, b) in enumerate(zip(lo, hi)):
            for gx in range(a[0], b[0] + 1):
                for gy in range(a[1], b[1] + 1):
                    self.bins.setdefault((gx, gy), []).append(i)

    def heights(self, x, y):
        """Every z where the vertical line through (x, y) meets a triangle."""
        cand = self.bins.get((math.floor(x), math.floor(y)))
        if not cand:
            return []
        t = self.tris[cand]
        a, b, c = t[:, 0], t[:, 1], t[:, 2]
        # Barycentric coordinates of (x, y) in each triangle's xy projection.
        v0, v1 = b[:, :2] - a[:, :2], c[:, :2] - a[:, :2]
        v2 = np.array([x, y]) - a[:, :2]
        den = v0[:, 0] * v1[:, 1] - v1[:, 0] * v0[:, 1]
        ok = np.abs(den) > 1e-12
        den = np.where(ok, den, 1.0)
        u = (v2[:, 0] * v1[:, 1] - v1[:, 0] * v2[:, 1]) / den
        v = (v0[:, 0] * v2[:, 1] - v2[:, 0] * v0[:, 1]) / den
        hit = ok & (u >= -1e-9) & (v >= -1e-9) & (u + v <= 1 + 1e-9)
        z = a[:, 2] + u * (b[:, 2] - a[:, 2]) + v * (c[:, 2] - a[:, 2])
        return list(z[hit])


def load_scenery():
    """(ground, water, obstacles): ground and water Surfaces, plus a list of
    world-frame AABBs (min xyz, max xyz) for every tree trunk and crown."""
    model = ET.parse(MODELS / 'blue_mountains' / 'model.sdf').getroot().find('model')
    ground, water, obstacles = [], [], []
    for link in model.findall('link'):
        link_tf = pose_matrix(link.findtext('pose'))
        for col in link.findall('collision'):
            tf = link_tf @ pose_matrix(col.findtext('pose'))
            geom = col.find('geometry')
            uri = geom.findtext('mesh/uri')
            if uri and uri.split('/')[-1][0].isdigit():
                ground.append(mesh_tris(geom, tf))  # terrain, rock, talus
                continue
            if uri:
                pts = mesh_tris(geom, tf).reshape(-1, 3)
            elif geom.find('cylinder') is not None:
                r = float(geom.findtext('cylinder/radius'))
                h = float(geom.findtext('cylinder/length'))
                pts = np.array([[sx * r, sy * r, sz * h / 2] for sx in (-1, 1)
                                for sy in (-1, 1) for sz in (-1, 1)])
                pts = pts @ tf[:3, :3].T + tf[:3, 3]
            else:
                s = np.array(geom.findtext('box/size').split(), float) / 2
                pts = np.array([[sx, sy, sz] for sx in (-1, 1)
                                for sy in (-1, 1) for sz in (-1, 1)]) * s
                pts = pts @ tf[:3, :3].T + tf[:3, 3]
            obstacles.append((pts.min(axis=0), pts.max(axis=0)))
        for vis in link.findall('visual'):
            uri = vis.findtext('geometry/mesh/uri') or ''
            if 'water' in uri:
                water.append(mesh_tris(vis.find('geometry'), link_tf @ pose_matrix(vis.findtext('pose'))))
    return Surface(np.concatenate(ground)), Surface(np.concatenate(water)), obstacles


def footprint_points(animal, x, y, yaw, step=0.12):
    (x0, x1, y0, y1), _ = FOOTPRINT[animal]
    cw, sw = math.cos(yaw), math.sin(yaw)
    for lx in np.linspace(x0, x1, max(2, int((x1 - x0) / step) + 1)):
        for ly in np.linspace(y0, y1, max(2, int((y1 - y0) / step) + 1)):
            yield x + cw * lx - sw * ly, y + sw * lx + cw * ly


def rotation(roll, pitch, yaw):
    return pose_matrix(f'0 0 0 {roll} {pitch} {yaw}')[:3, :3]


def try_spot(animal, x, y, yaw, ground, water, obstacles, max_slope, max_step, gap):
    """(z, roll, pitch) to set the animal down with, or None if (x, y, yaw)
    is no good."""
    samples = []
    for px, py in footprint_points(animal, x, y, yaw):
        hits = ground.heights(px, py)
        if not hits:
            return None  # off the edge of the scenery
        z = max(hits)
        if any(w > z for w in water.heights(px, py)):
            return None  # in the river
        samples.append((px, py, z))
    s = np.array(samples)

    # Ground plane z = a + b (x - x0) + c (y - y0) through the samples.
    A = np.column_stack([np.ones(len(s)), s[:, 0] - x, s[:, 1] - y])
    (a, b, c), *_ = np.linalg.lstsq(A, s[:, 2], rcond=None)
    if math.hypot(b, c) > max_slope or np.abs(A @ (a, b, c) - s[:, 2]).max() > max_step:
        return None

    # Turn the model about z by yaw, then tilt its z axis onto the plane's
    # normal (in SDF's roll-pitch-yaw order the yaw goes last, so solve for
    # roll and pitch in the yawed frame).
    n = np.array([-b, -c, 1.0]) / math.sqrt(1 + b * b + c * c)
    nl = rotation(0, 0, -yaw) @ n
    pitch = math.atan2(nl[0], nl[2])
    roll = -math.asin(max(-1.0, min(1.0, nl[1])))
    R = rotation(roll, pitch, yaw)

    # Lowest z for the model origin that keeps every footprint sample point
    # (at the model's z = 0) on or above the ground under it.
    local = [(R.T @ (px - x, py - y, 0.0)) for px, py, _ in samples]
    base = max(gz - (R @ (l[0], l[1], 0.0))[2] for l, (_, _, gz) in zip(local, samples)) + gap

    # Anything of a tree within 0.4 m of the animal's box.
    (x0, x1, y0, y1), height = FOOTPRINT[animal]
    reach = math.hypot(max(-x0, x1), max(-y0, y1)) + 0.4
    for lo, hi in obstacles:
        if (lo[0] - reach < x < hi[0] + reach and lo[1] - reach < y < hi[1] + reach
                and lo[2] < base + height + 0.4 and hi[2] > base - 0.2):
            return None
    return base, roll, pitch


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--kangaroos', type=int, default=6)
    ap.add_argument('--wombats', type=int, default=6)
    ap.add_argument('--seed', type=int, default=41068)
    ap.add_argument('--spacing', type=float, default=5.0,
                    help='minimum distance between animals (m)')
    ap.add_argument('--max-slope', type=float, default=0.18,
                    help='steepest ground to put an animal on (rise over run, 0.18 = 10 deg)')
    ap.add_argument('--max-step', type=float, default=0.05,
                    help='most the ground may stray from a flat plane under one animal (m)')
    ap.add_argument('--gap', type=float, default=0.02,
                    help='height above the highest ground sample to set each animal (m)')
    args = ap.parse_args()

    rng = random.Random(args.seed)
    ground, water, obstacles = load_scenery()
    clear = list(KEEP_CLEAR)
    placed = []
    todo = ['kangaroo'] * args.kangaroos + ['wombat'] * args.wombats
    rng.shuffle(todo)
    for animal in todo:
        for _ in range(5000):
            x, y = rng.uniform(*X_RANGE), rng.uniform(*Y_RANGE)
            if any(math.hypot(x - cx, y - cy) < r for cx, cy, r in clear):
                continue
            yaw = rng.uniform(-math.pi, math.pi)
            spot = try_spot(animal, x, y, yaw, ground, water, obstacles,
                            args.max_slope, args.max_step, args.gap)
            if spot is not None:
                break
        else:
            raise SystemExit(f'No room found for another {animal}; try fewer or a smaller --spacing.')
        n = 1 + sum(a == animal for a, *_ in placed)
        z, roll, pitch = spot
        placed.append((animal, n, x, y, z, roll, pitch, yaw))
        clear.append((x, y, args.spacing))

    lines = [BEGIN,
             '    <!-- Animals scattered over the scenery, each set down on the ground',
             '         under its footprint. Dynamic, like the two above. -->']
    for animal, n, x, y, z, roll, pitch, yaw in sorted(placed):
        lines += ['    <include>',
                  f'      <uri>model://{animal}</uri>',
                  f'      <name>{animal}_scatter_{n}</name>',
                  f'      <pose>{x:.2f} {y:.2f} {z:.3f} {roll:.3f} {pitch:.3f} {yaw:.3f}</pose>',
                  '    </include>']
        print(f'{animal:8s} {n:2d}  ({x:6.2f}, {y:6.2f})  z {z:6.3f}  '
              f'tilt {math.degrees(math.hypot(roll, pitch)):4.1f} deg  yaw {yaw:6.3f}')
    lines.append('    ' + END)
    block = '\n'.join(lines)

    text = WORLD.read_text()
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + '.*?' + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        anchor = '    <include>\n      <uri>model://blue_mountains</uri>'
        assert anchor in text, 'could not find where to put the animals in ' + str(WORLD)
        text = text.replace(anchor, '    ' + block + '\n' + anchor, 1)
    WORLD.write_text(text)
    print(f'Wrote {len(placed)} animals to {WORLD.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
